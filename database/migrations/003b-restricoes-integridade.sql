-- U01 complementar / #33. MySQL >= 8.0.16. Backup verificado e SEM escritas concorrentes.
-- DDL tem commit implicito. Nunca usar --force. Leia database/README.md.
-- CREATE PROCEDURE sem IF EXISTS: nao substitui objetos de outra origem.
-- Se CALL falhar, a rotina permanece para diagnostico; siga o procedimento de retomada no README.
SET NAMES utf8mb4;
SET SESSION time_zone = '+00:00';
SET SESSION sql_mode = CONCAT_WS(',', @@SESSION.sql_mode, 'STRICT_ALL_TABLES');
-- Pre-requisito: 003a e preenchimento EXPLICITO das apresentacoes, sem inferir texto desconhecido.
DELIMITER $$
CREATE PROCEDURE pf33_consolidar_integridade()
SQL SECURITY INVOKER
BEGIN

    IF VERSION() LIKE '%MariaDB%' OR CAST(SUBSTRING_INDEX(VERSION(), '.', 1) AS UNSIGNED) < 8
        OR (CAST(SUBSTRING_INDEX(VERSION(), '.', 1) AS UNSIGNED) = 8
            AND CAST(SUBSTRING_INDEX(SUBSTRING_INDEX(VERSION(), '.', 2), '.', -1) AS UNSIGNED) = 0
            AND CAST(SUBSTRING_INDEX(SUBSTRING_INDEX(VERSION(), '.', 3), '.', -1) AS UNSIGNED) < 16) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: requer MySQL 8.0.16 ou superior, nao MariaDB.';
    END IF;
    IF (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME IN ('MEDICAMENTO','FARMACIA','MEDICAMENTO_FARMACIA','HISTORICO_PRECO'))
        <> 25 + (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
            AND TABLE_NAME = 'MEDICAMENTO' AND COLUMN_NAME = 'APRESENTACAO') THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: colunas extras fora do esquema esperado; revisar antes de migrar.';
    END IF;
    IF (SELECT COUNT(*) FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE() AND INDEX_NAME = 'PRIMARY'
        AND SEQ_IN_INDEX = 1 AND SUB_PART IS NULL AND (
        (TABLE_NAME = 'MEDICAMENTO' AND COLUMN_NAME = 'ID_MEDICAMENTO') OR
        (TABLE_NAME = 'FARMACIA' AND COLUMN_NAME = 'ID_FARMACIA') OR
        (TABLE_NAME = 'MEDICAMENTO_FARMACIA' AND COLUMN_NAME = 'ID_MEDICAMENTO_FARMACIA') OR
        (TABLE_NAME = 'HISTORICO_PRECO' AND COLUMN_NAME = 'ID_HISTORICO_PRECO'))) <> 4
        OR (SELECT COUNT(*) FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE() AND INDEX_NAME = 'PRIMARY'
            AND TABLE_NAME IN ('MEDICAMENTO','FARMACIA','MEDICAMENTO_FARMACIA','HISTORICO_PRECO')) <> 4 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: chaves primarias divergentes.';
    END IF;
    IF (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
        AND LEFT(COLUMN_NAME,3) = 'ID_' AND TABLE_NAME IN ('MEDICAMENTO','FARMACIA','MEDICAMENTO_FARMACIA','HISTORICO_PRECO')
        AND DATA_TYPE = 'int' AND COLUMN_TYPE NOT LIKE '%unsigned%' AND IS_NULLABLE = 'NO') <> 7
        OR (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
            AND TABLE_NAME = 'MEDICAMENTO' AND (
            (COLUMN_NAME IN ('NOME','PRINCIPIO_ATIVO') AND CHARACTER_MAXIMUM_LENGTH = 150) OR
            (COLUMN_NAME = 'CATEGORIA' AND CHARACTER_MAXIMUM_LENGTH = 100) OR
            (COLUMN_NAME = 'DOSAGEM' AND CHARACTER_MAXIMUM_LENGTH = 50) OR
            (COLUMN_NAME = 'DESCRICAO' AND CHARACTER_MAXIMUM_LENGTH = 255))
            AND DATA_TYPE = 'varchar' AND IS_NULLABLE = 'NO') <> 5 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: IDs ou atributos do medicamento divergentes.';
    END IF;
    IF (SELECT COUNT(*) FROM information_schema.CHECK_CONSTRAINTS
        WHERE CONSTRAINT_SCHEMA = DATABASE() AND (
        (CONSTRAINT_NAME = 'CK_OFERTA_PRECO_POSITIVO' AND
            REPLACE(REPLACE(REPLACE(REPLACE(LOWER(CHECK_CLAUSE),'`',''),' ',''),'(',''),')','') = 'preco>0') OR
        (CONSTRAINT_NAME = 'CK_OFERTA_DISPONIVEL' AND
            REPLACE(REPLACE(REPLACE(REPLACE(LOWER(CHECK_CLAUSE),'`',''),' ',''),'(',''),')','') = 'disponivelin0,1'))) <> 2 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: expressoes CHECK da oferta divergentes.';
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE()
        AND INDEX_NAME IN ('UQ_MEDICAMENTO_IDENTIDADE','UQ_HISTORICO_OFERTA_DATA')) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: nome de indice reservado ja existe.';
    END IF;
    IF EXISTS (SELECT 1 FROM HISTORICO_PRECO h LEFT JOIN MEDICAMENTO_FARMACIA o
            USING (ID_MEDICAMENTO_FARMACIA) WHERE o.ID_MEDICAMENTO_FARMACIA IS NULL)
        OR EXISTS (SELECT 1 FROM MEDICAMENTO_FARMACIA o LEFT JOIN MEDICAMENTO m USING (ID_MEDICAMENTO)
            LEFT JOIN FARMACIA f USING (ID_FARMACIA) WHERE m.ID_MEDICAMENTO IS NULL OR f.ID_FARMACIA IS NULL) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: registros orfaos preexistentes; revisar FKs e dados sem exclusao automatica.';
    END IF;

    IF DATABASE() IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: selecione explicitamente o banco alvo.';
    END IF;
    IF (SELECT COUNT(*) FROM information_schema.TABLES
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME IN
        ('MEDICAMENTO','FARMACIA','MEDICAMENTO_FARMACIA','HISTORICO_PRECO')
        AND TABLE_TYPE = 'BASE TABLE' AND ENGINE = 'InnoDB') <> 4 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: esperadas quatro tabelas U01 InnoDB; confira nomes e engine.';
    END IF;
    -- Comparar metadados com os identificadores canonicos; suporta lower_case_table_names=1.
    IF (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND (
        (TABLE_NAME = 'MEDICAMENTO' AND COLUMN_NAME IN
            ('ID_MEDICAMENTO','NOME','PRINCIPIO_ATIVO','CATEGORIA','DOSAGEM','DESCRICAO')) OR
        (TABLE_NAME = 'FARMACIA' AND COLUMN_NAME IN
            ('ID_FARMACIA','NOME','ENDERECO','CEP','LATITUDE','LONGITUDE','HORARIO_ABERTURA','HORARIO_FECHAMENTO','DELIVERY')) OR
        (TABLE_NAME = 'MEDICAMENTO_FARMACIA' AND COLUMN_NAME IN
            ('ID_MEDICAMENTO_FARMACIA','ID_MEDICAMENTO','ID_FARMACIA','PRECO','DISPONIVEL','DATA_ATUALIZACAO')) OR
        (TABLE_NAME = 'HISTORICO_PRECO' AND COLUMN_NAME IN
            ('ID_HISTORICO_PRECO','ID_MEDICAMENTO_FARMACIA','PRECO','DATA_REGISTRO')))) <> 25 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: faltam colunas do esquema U01 esperado.';
    END IF;
    IF (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND (
        (TABLE_NAME = 'HISTORICO_PRECO' AND COLUMN_NAME = 'DATA_REGISTRO' AND DATA_TYPE = 'date' AND IS_NULLABLE = 'NO') OR
        (TABLE_NAME IN ('HISTORICO_PRECO','MEDICAMENTO_FARMACIA') AND COLUMN_NAME = 'PRECO'
            AND DATA_TYPE = 'decimal' AND NUMERIC_PRECISION = 10 AND NUMERIC_SCALE = 2 AND IS_NULLABLE = 'NO') OR
        (TABLE_NAME = 'FARMACIA' AND COLUMN_NAME = 'CEP' AND DATA_TYPE = 'varchar'
            AND CHARACTER_MAXIMUM_LENGTH = 8 AND IS_NULLABLE = 'YES') OR
        (TABLE_NAME = 'FARMACIA' AND COLUMN_NAME IN ('LATITUDE','LONGITUDE') AND DATA_TYPE = 'decimal'
            AND NUMERIC_PRECISION = 10 AND NUMERIC_SCALE = 7 AND IS_NULLABLE = 'YES') OR
        (TABLE_NAME = 'MEDICAMENTO' AND COLUMN_NAME IN ('NOME','DOSAGEM') AND DATA_TYPE = 'varchar'
            AND IS_NULLABLE = 'NO' AND COLLATION_NAME = 'utf8mb4_unicode_ci') OR
        (TABLE_NAME = 'MEDICAMENTO_FARMACIA' AND COLUMN_NAME = 'DISPONIVEL'
            AND DATA_TYPE = 'tinyint' AND IS_NULLABLE = 'NO') OR
        (TABLE_NAME = 'MEDICAMENTO_FARMACIA' AND COLUMN_NAME = 'DATA_ATUALIZACAO'
            AND DATA_TYPE = 'timestamp' AND IS_NULLABLE = 'YES' AND EXTRA LIKE '%on update CURRENT_TIMESTAMP%'))) <> 10 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: tipos, nulabilidade, collation ou consolidacao U01 divergentes; revisar, sem conversao automatica.';
    END IF;
    IF (SELECT COUNT(*) FROM information_schema.KEY_COLUMN_USAGE WHERE TABLE_SCHEMA = DATABASE()
        AND REFERENCED_TABLE_SCHEMA = DATABASE() AND (
        (TABLE_NAME = 'HISTORICO_PRECO' AND COLUMN_NAME = 'ID_MEDICAMENTO_FARMACIA'
            AND REFERENCED_TABLE_NAME = 'MEDICAMENTO_FARMACIA' AND REFERENCED_COLUMN_NAME = 'ID_MEDICAMENTO_FARMACIA') OR
        (TABLE_NAME = 'MEDICAMENTO_FARMACIA' AND COLUMN_NAME = 'ID_MEDICAMENTO'
            AND REFERENCED_TABLE_NAME = 'MEDICAMENTO' AND REFERENCED_COLUMN_NAME = 'ID_MEDICAMENTO') OR
        (TABLE_NAME = 'MEDICAMENTO_FARMACIA' AND COLUMN_NAME = 'ID_FARMACIA'
            AND REFERENCED_TABLE_NAME = 'FARMACIA' AND REFERENCED_COLUMN_NAME = 'ID_FARMACIA'))) <> 3 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: chaves estrangeiras U01 divergentes.';
    END IF;
    IF (SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS WHERE CONSTRAINT_SCHEMA = DATABASE()
        AND TABLE_NAME IN ('MEDICAMENTO','FARMACIA','MEDICAMENTO_FARMACIA','HISTORICO_PRECO')) <> 10
        OR (SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS WHERE CONSTRAINT_SCHEMA = DATABASE()
            AND TABLE_NAME = 'MEDICAMENTO_FARMACIA' AND CONSTRAINT_TYPE = 'CHECK' AND ENFORCED = 'YES'
            AND CONSTRAINT_NAME IN ('CK_OFERTA_PRECO_POSITIVO','CK_OFERTA_DISPONIVEL')) <> 2
        OR (SELECT COUNT(*) FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE()
            AND TABLE_NAME = 'MEDICAMENTO_FARMACIA' AND INDEX_NAME = 'UQ_MEDICAMENTO_FARMACIA'
            AND NON_UNIQUE = 0 AND SUB_PART IS NULL AND
            ((SEQ_IN_INDEX = 1 AND COLUMN_NAME = 'ID_MEDICAMENTO') OR
             (SEQ_IN_INDEX = 2 AND COLUMN_NAME = 'ID_FARMACIA'))) <> 2 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: constraints U01 divergentes, extras ou 003 ja aplicada; inspecione SHOW CREATE TABLE.';
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.TABLE_CONSTRAINTS WHERE CONSTRAINT_SCHEMA = DATABASE()
        AND CONSTRAINT_NAME IN ('CK_HISTORICO_PRECO_POSITIVO','UQ_HISTORICO_OFERTA_DATA',
        'CK_FARMACIA_CEP','CK_FARMACIA_LATITUDE','CK_FARMACIA_LONGITUDE','CK_FARMACIA_COORDENADAS',
        'CK_MEDICAMENTO_APRESENTACAO','UQ_MEDICAMENTO_IDENTIDADE')) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: nome de constraint reservado ja existe; nenhuma constraint sera substituida.';
    END IF;

    IF (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = 'MEDICAMENTO' AND COLUMN_NAME = 'APRESENTACAO' AND DATA_TYPE = 'varchar'
        AND CHARACTER_MAXIMUM_LENGTH = 150 AND COLLATION_NAME = 'utf8mb4_unicode_ci'
        AND IS_NULLABLE = 'YES') <> 1 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003b: esperada APRESENTACAO anulavel criada pela 003a.';
    END IF;

    SELECT ID_HISTORICO_PRECO, ID_MEDICAMENTO_FARMACIA, PRECO, DATA_REGISTRO
        FROM HISTORICO_PRECO WHERE PRECO <= 0;
    SELECT ID_MEDICAMENTO_FARMACIA, DATA_REGISTRO, COUNT(*) AS quantidade
        FROM HISTORICO_PRECO GROUP BY ID_MEDICAMENTO_FARMACIA, DATA_REGISTRO HAVING COUNT(*) > 1;
    SELECT ID_FARMACIA, CEP, LATITUDE, LONGITUDE FROM FARMACIA
        WHERE (CEP IS NOT NULL AND NOT (CHAR_LENGTH(CEP) = 8 AND REGEXP_LIKE(CEP, '^[0-9]{8}$', 'c')))
            OR LATITUDE NOT BETWEEN -90 AND 90 OR LONGITUDE NOT BETWEEN -180 AND 180
            OR (LATITUDE IS NULL) <> (LONGITUDE IS NULL);
    IF EXISTS (SELECT 1 FROM HISTORICO_PRECO WHERE PRECO <= 0) OR EXISTS (
        SELECT 1 FROM HISTORICO_PRECO GROUP BY ID_MEDICAMENTO_FARMACIA, DATA_REGISTRO HAVING COUNT(*) > 1) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: historico tem preco invalido ou oferta/data repetida; revisar linhas listadas, sem exclusao automatica.';
    END IF;
    IF EXISTS (SELECT 1 FROM FARMACIA WHERE
        (CEP IS NOT NULL AND NOT (CHAR_LENGTH(CEP) = 8 AND REGEXP_LIKE(CEP, '^[0-9]{8}$', 'c')))
        OR LATITUDE NOT BETWEEN -90 AND 90 OR LONGITUDE NOT BETWEEN -180 AND 180
        OR (LATITUDE IS NULL) <> (LONGITUDE IS NULL)) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003: farmacia tem CEP/coordenadas invalidos; revisar IDs listados.';
    END IF;

    SELECT ID_MEDICAMENTO, NOME, DOSAGEM, APRESENTACAO FROM MEDICAMENTO
        WHERE APRESENTACAO IS NULL OR CHAR_LENGTH(TRIM(APRESENTACAO)) = 0;
    SELECT NOME, DOSAGEM, APRESENTACAO, COUNT(*) AS quantidade FROM MEDICAMENTO
        GROUP BY NOME, DOSAGEM, APRESENTACAO HAVING COUNT(*) > 1;
    IF EXISTS (SELECT 1 FROM MEDICAMENTO WHERE APRESENTACAO IS NULL OR CHAR_LENGTH(TRIM(APRESENTACAO)) = 0) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003b: apresentacoes desconhecidas/vazias; preencher explicitamente por ID antes de consolidar.';
    END IF;
    IF EXISTS (SELECT 1 FROM MEDICAMENTO GROUP BY NOME, DOSAGEM, APRESENTACAO HAVING COUNT(*) > 1) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '003b: identidades duplicadas sob utf8mb4_unicode_ci; nao renumerar nem fundir automaticamente.';
    END IF;
    -- Preflight completo ANTES do primeiro ALTER. Cada ALTER e atomico, o conjunto nao.
    ALTER TABLE MEDICAMENTO
        MODIFY COLUMN APRESENTACAO VARCHAR(150) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
        ADD CONSTRAINT CK_MEDICAMENTO_APRESENTACAO CHECK (CHAR_LENGTH(TRIM(APRESENTACAO)) > 0),
        ADD CONSTRAINT UQ_MEDICAMENTO_IDENTIDADE UNIQUE (NOME, DOSAGEM, APRESENTACAO);
    ALTER TABLE FARMACIA
        ADD CONSTRAINT CK_FARMACIA_CEP CHECK (CEP IS NULL OR (CHAR_LENGTH(CEP) = 8 AND REGEXP_LIKE(CEP, '^[0-9]{8}$', 'c'))),
        ADD CONSTRAINT CK_FARMACIA_LATITUDE CHECK (LATITUDE IS NULL OR LATITUDE BETWEEN -90 AND 90),
        ADD CONSTRAINT CK_FARMACIA_LONGITUDE CHECK (LONGITUDE IS NULL OR LONGITUDE BETWEEN -180 AND 180),
        ADD CONSTRAINT CK_FARMACIA_COORDENADAS CHECK ((LATITUDE IS NULL) = (LONGITUDE IS NULL));
    ALTER TABLE HISTORICO_PRECO
        ADD CONSTRAINT CK_HISTORICO_PRECO_POSITIVO CHECK (PRECO > 0),
        ADD CONSTRAINT UQ_HISTORICO_OFERTA_DATA UNIQUE (ID_MEDICAMENTO_FARMACIA, DATA_REGISTRO);
    SELECT '003b concluida. USUARIO permanece ate a etapa opcional 003c autorizada por alvo.' AS resultado;
END$$
DELIMITER ;
CALL pf33_consolidar_integridade();
DROP PROCEDURE pf33_consolidar_integridade;
