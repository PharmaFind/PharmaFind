-- Verificacao sem alteracao de registros, apos criar/reaplicar SOMENTE o clone descartavel aprovado.
-- Todos os campos booleanos devem ser 1; os tres hashes devem ser iguais antes/depois da reaplicacao.
SET SESSION time_zone = '+00:00';
SET SESSION group_concat_max_len = 8192;
SELECT DATABASE() AS banco, VERSION() AS versao_servidor,
    (SELECT COUNT(*) = 4 FROM information_schema.tables
        WHERE table_schema = DATABASE() AND table_type = 'BASE TABLE' AND engine = 'InnoDB') AS esquema_ok,
    (SELECT COUNT(*) = 6 FROM MEDICAMENTO) AS medicamentos_ok,
    (SELECT COUNT(*) = 4 FROM FARMACIA) AS farmacias_ok,
    (SELECT COUNT(*) = 12 AND SUM(DISPONIVEL = 1) = 8 AND SUM(DISPONIVEL = 0) = 4
        FROM MEDICAMENTO_FARMACIA) AS ofertas_ok,
    (SELECT COUNT(*) = 0 FROM MEDICAMENTO_FARMACIA WHERE ID_MEDICAMENTO = 1004) AS sem_ofertas_ok,
    (SELECT COUNT(*) = 3 AND SUM(DISPONIVEL) = 0 FROM MEDICAMENTO_FARMACIA WHERE ID_MEDICAMENTO = 1003) AS indisponiveis_ok,
    (SELECT COUNT(*) = 0 FROM HISTORICO_PRECO) AS historico_intacto_ok;
SELECT 'medicamentos' AS conjunto, SHA2(GROUP_CONCAT(SHA2(JSON_ARRAY(ID_MEDICAMENTO, NOME,
    PRINCIPIO_ATIVO, CATEGORIA, DOSAGEM, APRESENTACAO, DESCRICAO), 256) ORDER BY ID_MEDICAMENTO SEPARATOR ''), 256) AS hash_dados
FROM MEDICAMENTO
UNION ALL
SELECT 'farmacias', SHA2(GROUP_CONCAT(SHA2(JSON_ARRAY(ID_FARMACIA, NOME, ENDERECO, CEP,
    LATITUDE, LONGITUDE, HORARIO_ABERTURA, HORARIO_FECHAMENTO, DELIVERY), 256)
    ORDER BY ID_FARMACIA SEPARATOR ''), 256) FROM FARMACIA
UNION ALL
SELECT 'ofertas', SHA2(GROUP_CONCAT(SHA2(JSON_ARRAY(ID_MEDICAMENTO_FARMACIA, ID_MEDICAMENTO,
    ID_FARMACIA, PRECO, DISPONIVEL, DATA_ATUALIZACAO), 256)
    ORDER BY ID_MEDICAMENTO_FARMACIA SEPARATOR ''), 256) FROM MEDICAMENTO_FARMACIA;
