-- Usar modo SQL estrito em todas as conexoes e sessoes em UTC.
-- Banco existente: seguir migrations/ e README.md, sem recriar tabelas.
SET SESSION time_zone = '+00:00';
SET SESSION sql_mode = CONCAT_WS(',', @@SESSION.sql_mode, 'STRICT_ALL_TABLES');

CREATE TABLE FARMACIA(
    ID_FARMACIA INT AUTO_INCREMENT,
    NOME VARCHAR(150) NOT NULL,
    ENDERECO VARCHAR(255) NOT NULL,
    CEP VARCHAR(8),
    LATITUDE DECIMAL(10,7),
    LONGITUDE DECIMAL(10,7),
    HORARIO_ABERTURA TIME,
    HORARIO_FECHAMENTO TIME,
    DELIVERY BOOLEAN,
    CONSTRAINT CK_FARMACIA_CEP CHECK (CEP IS NULL OR (CHAR_LENGTH(CEP) = 8 AND REGEXP_LIKE(CEP, '^[0-9]{8}$', 'c'))),
    CONSTRAINT CK_FARMACIA_LATITUDE CHECK (LATITUDE IS NULL OR LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_FARMACIA_LONGITUDE CHECK (LONGITUDE IS NULL OR LONGITUDE BETWEEN -180 AND 180),
    CONSTRAINT CK_FARMACIA_COORDENADAS CHECK ((LATITUDE IS NULL) = (LONGITUDE IS NULL)),
    PRIMARY KEY(ID_FARMACIA)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE MEDICAMENTO(
    ID_MEDICAMENTO INT AUTO_INCREMENT,
    NOME VARCHAR(150) NOT NULL,
    PRINCIPIO_ATIVO VARCHAR(150) NOT NULL,
    CATEGORIA VARCHAR(100) NOT NULL,
    DOSAGEM VARCHAR(50) NOT NULL,
    APRESENTACAO VARCHAR(150) NOT NULL,
    DESCRICAO VARCHAR(255) NOT NULL,
    CONSTRAINT CK_MEDICAMENTO_APRESENTACAO CHECK (CHAR_LENGTH(TRIM(APRESENTACAO)) > 0),
    CONSTRAINT UQ_MEDICAMENTO_IDENTIDADE UNIQUE (NOME, DOSAGEM, APRESENTACAO),
    PRIMARY KEY(ID_MEDICAMENTO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE MEDICAMENTO_FARMACIA(
    ID_MEDICAMENTO_FARMACIA INT AUTO_INCREMENT,
    ID_MEDICAMENTO INT NOT NULL,
    ID_FARMACIA INT NOT NULL,
    PRECO DECIMAL(10,2) NOT NULL,
    DISPONIVEL BOOLEAN NOT NULL,
    -- NULL preserva datas antigas desconhecidas; novas ofertas recebem o instante atual.
    DATA_ATUALIZACAO TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT CK_OFERTA_PRECO_POSITIVO CHECK (PRECO > 0),
    CONSTRAINT CK_OFERTA_DISPONIVEL CHECK (DISPONIVEL IN (0, 1)),
    CONSTRAINT FK_ID_MEDICAMENTO FOREIGN KEY(ID_MEDICAMENTO) REFERENCES MEDICAMENTO(ID_MEDICAMENTO)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT FK_ID_FARMACIA FOREIGN KEY(ID_FARMACIA) REFERENCES FARMACIA(ID_FARMACIA)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT UQ_MEDICAMENTO_FARMACIA UNIQUE(ID_MEDICAMENTO, ID_FARMACIA),
    PRIMARY KEY(ID_MEDICAMENTO_FARMACIA)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE HISTORICO_PRECO(
    ID_HISTORICO_PRECO INT AUTO_INCREMENT,
    ID_MEDICAMENTO_FARMACIA INT NOT NULL,
    PRECO DECIMAL(10,2) NOT NULL,
    DATA_REGISTRO DATE NOT NULL,
    CONSTRAINT CK_HISTORICO_PRECO_POSITIVO CHECK (PRECO > 0),
    CONSTRAINT UQ_HISTORICO_OFERTA_DATA UNIQUE (ID_MEDICAMENTO_FARMACIA, DATA_REGISTRO),
    CONSTRAINT FK_ID_MEDICAMENTO_FARMACIA FOREIGN KEY(ID_MEDICAMENTO_FARMACIA) REFERENCES MEDICAMENTO_FARMACIA(ID_MEDICAMENTO_FARMACIA),
    PRIMARY KEY(ID_HISTORICO_PRECO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
